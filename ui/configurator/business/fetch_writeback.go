// File fetch_writeback.go — запись результата one-shot fetch'а обратно в
// модель (SPEC 118 W6, хвост ревью W3).
//
// Проблема, которую решает файл. Ручное обновление подписки (кнопка Refresh в
// списке источников и «Fetch now» на вкладке Preview) работает на СНИМКЕ:
// снимок берётся на UI-потоке, горутина качает сеть и мутирует снимок, потом
// снимок записывается обратно в модель. Пока горутина летит, пользователь
// вправе править ту же запись — переименовать, сменить тег-политику, снять
// галку с узла, включить свёртку. Запись снимка ЦЕЛИКОМ откатывала бы все эти
// правки к состоянию на момент старта fetch'а: пользователь видел, как его
// правка исчезает через две секунды после нажатия, и повода связать это с
// обновлением подписки у него нет.
//
// Решение — та же логика, что уже держит Save окна источника
// (mergeEditedSourceIntoModel): у fetch'а есть СВОИ поля, и только их он
// вправе занести. Всё остальное принадлежит живой записи.
//
// Ревизия модели (SPEC 117) — дешёвый признак «модель трогали»: пока она не
// менялась, снимок и живая запись — одно и то же, и запись целиком безопасна
// (это же сохраняет поля, о которых fetch-слой знать не обязан). Изменилась —
// переносим только результат fetch'а.
package business

import (
	corestate "singbox-launcher/core/state"
	wizardmodels "singbox-launcher/ui/configurator/models"
)

// ApplyFetchSnapshot заносит результат one-shot fetch'а в модель.
//
// snapshot — копия источника, которую мутировала горутина fetch'а;
// revAtStart — ревизия модели на момент снятия снимка.
//
// Возвращает true, если запись найдена и обновлена. Источник ищется по ID:
// слайс мог реаллоцироваться (пользователь добавил или удалил источник, пока
// горутина летела), и индекс, снятый до fetch'а, адресовал бы чужую запись.
func ApplyFetchSnapshot(m *wizardmodels.WizardModel, snapshot *corestate.Source, revAtStart uint64) bool {
	if m == nil || snapshot == nil || snapshot.ID == "" {
		return false
	}
	idx := -1
	for i := range m.Sources {
		if m.Sources[i].ID == snapshot.ID {
			idx = i
			break
		}
	}
	if idx < 0 {
		// Источник удалён, пока шёл fetch. Воскрешать его записью снимка
		// нельзя: удаление — осознанное действие пользователя, а fetch про
		// него ничего не знает.
		return false
	}
	if m.Revision == revAtStart {
		// Модель не трогали — снимок и есть актуальная запись плюс свежий
		// результат; пишем целиком, как раньше.
		m.Sources[idx] = *snapshot
		return true
	}
	// Модель правили, пока летел fetch. Занести имеем право только то, что
	// принадлежит fetch'у; остальное — правки пользователя, и они новее.
	applyFetchResultFields(&m.Sources[idx], snapshot)
	return true
}

// applyFetchResultFields — поля, которые ПРОИЗВОДИТ fetch, и только они.
//
// Состав узлов, диагностика попытки, заголовки провайдера и одноразовые
// отметки выключения (вердикт O2) рождаются в сети и в модели своего второго
// автора не имеют. URL, тег-политика, замена, skip, enabled источника и
// подпись — правки пользователя: их fetch не создаёт и переписывать не вправе.
//
// Отметки включённости узлов (`node.enabled`) приезжают в составе Nodes:
// merge подписки сам сохраняет их у совпавших узлов, а окно источника
// применяет свои тумблеры поверх живой записи журналом правок
// (mergeEditedSourceIntoModel) — второго хозяина у поля нет и здесь.
func applyFetchResultFields(live *corestate.Source, snapshot *corestate.Source) {
	live.Nodes = snapshot.Nodes
	live.UpdateStatus = snapshot.UpdateStatus
	live.Meta = snapshot.Meta
	live.PendingDisabled = snapshot.PendingDisabled
}
