// File versions.go — закладка для сервисных работ по событиям «лаунчер
// обновился» и «ядро обновилось» (SPEC 132).
//
// # Что это и чего тут НЕТ
//
// Списки работ ПУСТЫЕ, и это состояние по решению владельца, а не
// недоделка. Первым кандидатом на этот крючок было снятие вердиктов
// страховки «ядро не приняло узел» при смене ядра — от него отказались:
// ручного механизма достаточно (человек включает узел → вердикт стирается →
// следующая сборка проверит заново), и к нему добавлено правило «сменилось
// тело узла → вердикт снят, узел включён». Обход всех сохранённых состояний
// ради приговора, который человек снимает одним кликом, не окупается.
//
// Закладка при этом нужна: события «обновился лаунчер» и «обновилось ядро»
// сами по себе стоят того, чтобы быть видимыми. Релиз логирует только WARN
// (память `release-log-warn-only`), поэтому смена версии пишется именно
// WARN — иначе в логе с поля её не найти, а половина диагнозов начинается с
// вопроса «а что у вас менялось?».
//
// Следующая сервисная работа добавляется строкой в соответствующий список.
//
// # Порядок
//
// Отметка обновляется ПОСЛЕ работ: упали — отметка не обновилась, и на
// следующем старте событие поднимется снова. Поэтому каждая будущая работа
// обязана быть повторяемой без вреда.
//
// go1.20-совместимо (Win7-джоба): без slices/maps/min/max/clear.
package maintenance

import "singbox-launcher/internal/debuglog"

// OnLauncherVersionChanged — лаунчер обновился (или откатился).
//
// Работ пока нет; ошибка от будущей работы обязана вернуться сюда, чтобы
// вызывающий не обновил отметку.
func OnLauncherVersionChanged(old, current string) error {
	debuglog.WarnLog("maintenance: launcher updated %s → %s", old, current)
	// Список работ: пока пуст.
	return nil
}

// OnCoreVersionChanged — сменился бинарь ядра.
//
// Версию сообщает САМ бинарь (`sing-box version`), а не установщик: подмена
// ядра руками мимо кнопки — законный сценарий (память
// `core-binary-hands-off`), и привязка к установщику её бы не заметила.
func OnCoreVersionChanged(old, current string) error {
	debuglog.WarnLog("maintenance: core updated %s → %s", old, current)
	// Список работ: пока пуст. Снятия вердиктов страховки здесь НЕТ —
	// решение владельца, см. шапку файла.
	return nil
}
