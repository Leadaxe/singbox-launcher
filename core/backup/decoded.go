package backup

// Промежуточная форма импорта: ЗАПИСИ СОСТОЯНИЯ, уже снятые с файла, но ещё
// не слитые (SPEC 127 §6.2, W2.4).
//
// # Зачем шов
//
// Форматов файла два — 0.x (маппер `legacy_read_0x.go`) и 1.0 (`import10.go`,
// где записи уже лежат типами состояния). Правила слияния (BACKUP.md §9) при
// этом ОДНИ: подписки по `url` байт-в-байт, серверы по телу, папки по имени,
// цепочки и Направления по тегу, DNS «своё сильнее», `rules[]` — единственная
// полная замена, `vars` переносимые, `route.final` при известной цели, `warp`
// добавлением. Второй экземпляр этих правил под второй формат был бы вторым
// источником истины: разойдись они на строку — и один и тот же файл дал бы у
// пользователя два разных состояния.
//
// Поэтому импорт разрезан надвое: КАЖДЫЙ формат превращает файл в decodedFile
// (записи состояния + порядок + предупреждения разбора), и дальше работает
// ОДИН код слияния (`applyDecoded` в import.go + merge.go).
//
// # Почему порядок хранится списком, а не деревом
//
// Слияние 0.x идёт ОДНИМ проходом по `servers[]` в порядке файла: корневой
// узел, член папки, снова корневой. Порядок нормативен (§9 п. 3: «новые
// дописываются в конец в порядке файла»), и собери мы сперва папки, а потом
// корни — состав и порядок `s.Sources` после импорта поехали бы, а с ними и
// байты обратного экспорта. Поэтому decodedFile хранит ПЛОСКУЮ
// последовательность элементов ровно в порядке файла, а вид элемента говорит,
// по какому ключу его сливать.

import (
	"encoding/json"

	"singbox-launcher/core/config/configtypes"
	"singbox-launcher/core/state"
)

// decodedFile — файл бэкапа, переведённый в записи состояния.
//
// Всё, что здесь лежит, — уже типы `core/state`: слияние не знает, из какого
// формата это приехало, и знать не должно.
type decodedFile struct {
	// Sources — элементы в порядке файла (см. decodedSource).
	Sources []decodedSource
	// Directions — Направления канонической формы, переведённые во
	// внутреннюю. Порядок файла.
	Directions []configtypes.Direction
	// KnownTagsFromFile — теги, которые ПОРОДИТ сам импорт этого файла и о
	// которых принимающая сторона знать не может: у 0.x это позиционные
	// дериваты свёртки (`<N>:select`/`<N>:auto`, D-081). Без них правило и
	// route.final того же файла приезжали бы «в никуда».
	KnownTagsFromFile []string
	// Rules — записи правил в порядке файла (форма состояния v8).
	Rules []state.Rule
	// DNS — DNS-секция файла записями состояния; nil = секции нет.
	DNS *decodedDNS
	// Vars — переменные как есть: отбор переносимых делает слияние
	// (importVars), потому что отбор — это правило §9, а не форма файла.
	Vars map[string]string
	// RouteFinal — значение route.final; "" = ключа нет.
	RouteFinal string
	// Warp — регистрации сырым JSON (обе формы возят их одинаково).
	Warp []json.RawMessage
	// Warnings — потери РАЗБОРА (не слияния): чужой kind правила, ключи
	// identity, которые эта сторона не применяет, маска тегов и т. п.
	Warnings []Warning
}

// decodedSourceKind — по какому ключу слить элемент (§9).
type decodedSourceKind int

const (
	// decodedSubscription — по `url` байт-в-байт.
	decodedSubscription decodedSourceKind = iota
	// decodedServer — одиночный узел: по ТЕЛУ. Поле Folder непусто, если
	// узел — член папки с этим именем (§9 п. 3).
	decodedServer
	// decodedFolder — папка со своими настройками и составом (форма 1.0).
	// Сливается по имени; состав — по телу внутри неё.
	decodedFolder
	// decodedChain — по тегу.
	decodedChain
)

// decodedSource — один элемент sources[] в форме состояния.
type decodedSource struct {
	// Kind — по какому правилу сливать (не путать с state.SourceKind: у
	// папки из 0.x своего элемента нет вовсе, она собирается из членов).
	Kind decodedSourceKind
	// Src — запись состояния. У decodedFolder внутри Nodes лежит состав.
	Src state.Source
	// Folder — ИМЯ папки, членом которой узел является (0.x: поле `folder`
	// записи servers[]). Пусто = корневой узел.
	Folder string
	// FileFolderID — id этой папки В ФАЙЛЕ (1.0). Локальный id может
	// отличаться (совпавшая по имени папка держит свой), поэтому ссылки
	// detour/hops переписываются по карте «id файла → локальный id».
	FileFolderID string
	// FullSettings — несёт ли ФОРМАТ, из которого приехала запись, полный
	// набор настроек самого источника.
	//
	// Разница между входами, а не между записями. Форма 1.0 везёт настройки
	// контейнера целиком (§6.0: «настройки папки едут», relays_in_directions
	// у подписки), и у совпавшей записи они обязаны замещать локальные —
	// иначе главный сценарий переноса (на приёмнике папка с тем же именем
	// уже есть) молча теряет ровно то, ради чего 1.0 завёл им дом. Форма
	// 0.12 этих полей не несёт вовсе (BACKUP.md §9, backup_local_only_dropped),
	// и там их «отсутствие» значит «файл про них не знает», а не «сотри
	// своё»: применить нули 0.x значило бы стирать локальные настройки
	// импортом старого файла.
	FullSettings bool
	// Sections — БЫЛО ЛИ поле `sections` в файле у этой записи, а не «есть
	// ли в нём записи». Разница нормативна (§9 п. 2): поля нет → локальные
	// секции узла остаются нетронутыми; поле есть → замещает целиком, ВКЛЮЧАЯ
	// пустой набор (пользователь снял секции на другой машине, и «слить» тут
	// нечего — фрагменты не имеют ключа для сопоставления). Без флага пустой
	// набор был бы неотличим от молчания файла.
	Sections bool
	// MemberSections — то же по каждому члену папки, в порядке Src.Nodes.
	MemberSections []bool
}

// decodedDNS — DNS-секция файла записями состояния.
//
// Слияние (§9 п. 5) ключует серверы по `kind`+`tag`, а правила — по
// `kind`+`ref`+телу, и обе формы файла дают ровно эти поля; поэтому
// промежуточная форма — те же state.DNSServer/state.DNSRule, а не третья
// структура.
type decodedDNS struct {
	Servers []state.DNSServer
	Rules   []state.DNSRule
	// Final, Strategy, DefaultDomainResolver — три скаляра секции, и все три
	// живут по одному правилу: непустое значение файла замещает. Форма 0.12
	// третьего не знала вовсе, форма 1.0 знает (§6.0) — поле обязано быть
	// здесь, иначе писатель кладёт его в файл, а читатель роняет молча.
	Final                 string
	Strategy              string
	DefaultDomainResolver string
}
